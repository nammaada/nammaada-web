const stateByCode = new Map<string, IndiaState>();
const stateByName = new Map<string, IndiaState>();

for (const state of INDIA_STATES) {
  stateByCode.set(state.code.toUpperCase(), state);
  stateByName.set(state.name.toLowerCase().trim(), state);
}

// Additional code aliases
stateByCode.set("CT", stateByCode.get("CG")!);
stateByCode.set("DD", stateByCode.get("DN")!);
stateByCode.set("TG", stateByCode.get("TS")!);
stateByCode.set("UT", stateByCode.get("UK")!);
stateByCode.set("OR", stateByCode.get("OD")!);

export function getIndianStates(): readonly IndiaState[] {
  return INDIA_STATES;
}

export function findState(stateCodeOrName: string): IndiaState | undefined {
  if (!stateCodeOrName) return undefined;
  const trimmed = stateCodeOrName.trim();
  const byCode = stateByCode.get(trimmed.toUpperCase());
  if (byCode) return byCode;
  return stateByName.get(trimmed.toLowerCase());
}

export function getDistrictsForState(stateCodeOrName: string): readonly string[] {
  const state = findState(stateCodeOrName);
  return state ? state.districts : [];
}

export function isValidState(stateCodeOrName: string): boolean {
  return Boolean(findState(stateCodeOrName));
}

export function isValidDistrictForState(stateCodeOrName: string, districtName: string): boolean {
  const state = findState(stateCodeOrName);
  if (!state) return false;
  const cleanDistrict = districtName.trim().toLowerCase();
  return state.districts.some((d) => d.toLowerCase() === cleanDistrict);
}

export function getStateCanonicalName(stateCodeOrName: string): string {
  const state = findState(stateCodeOrName);
  return state ? state.name : stateCodeOrName.trim();
}

export function getStateCanonicalCode(stateCodeOrName: string): string {
  const state = findState(stateCodeOrName);
  return state ? state.code : stateCodeOrName.trim().toUpperCase();
}

